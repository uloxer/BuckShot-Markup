<# Generate native helper versions from the same authoritative source as the managed application. #>
param([string]$OutputPath = (Join-Path $PSScriptRoot 'generated-version.h'))
$ErrorActionPreference = 'Stop'
$source = Get-Content -LiteralPath (Join-Path $PSScriptRoot '../version.json') -Raw | ConvertFrom-Json
$match = [regex]::Match([string]$source.version, '^(\d+)\.(\d+)\.(\d+)$')
if (-not $match.Success) { throw 'src/version.json must contain a three-part numeric product version.' }
$parts = @($match.Groups[1].Value, $match.Groups[2].Value, $match.Groups[3].Value) | ForEach-Object { [int]$_ }
if (@($parts | Where-Object { $_ -gt 65535 }).Count) { throw 'Native version components must fit a Windows VERSIONINFO word.' }
$shortVersion = $parts -join '.'
$content = @"
// Generated by generate-version.ps1 from src/version.json. Do not edit.
#pragma once
#define BUCKSHOT_VERSION_NUMERIC $($parts -join ','),0
#define BUCKSHOT_VERSION_FULL "$shortVersion.0"
#define BUCKSHOT_VERSION_SHORT "$shortVersion"
"@
$content = $content.Replace("`r`n", "`n").Replace("`n", "`r`n") + "`r`n"
$OutputPath = [IO.Path]::GetFullPath($OutputPath)
# Both native projects may be built together; serialize the shared generated header.
$mutex = [Threading.Mutex]::new($false, 'Local\BuckShotMarkupNativeVersionHeader')
try {
    if (-not $mutex.WaitOne(30000)) { throw 'Timed out generating native product version.' }
    try {
        if (-not (Test-Path -LiteralPath $OutputPath) -or [IO.File]::ReadAllText($OutputPath) -cne $content) {
            [void][IO.Directory]::CreateDirectory((Split-Path $OutputPath -Parent))
            [IO.File]::WriteAllText($OutputPath, $content, [Text.Encoding]::ASCII)
        }
    }
    finally { $mutex.ReleaseMutex() }
}
finally { $mutex.Dispose() }
